/*
    Encapsulation is a core concept of OOP's that combines data & method  into a single unit called class like a protective jacket. The main goal of an encapsulation is to hide data from outer world but it reveals data then needed.

    In Dart, A library can hide their data members only discloses thought their functionality.

    Encapsulation process is used to secure data within OOP's.

    Rules of Encapsulation:
      1. Data members should be private by using underscore(_).
      2. Use getter() or setter() method to disclose implementation   details of a class.
      3. Properly use to access specifiers.

    Library in Dart : 
      By default every .dart file is a library.
      A library is a collection of function and classes.
      A library can be imported into another library using the import keyword.

